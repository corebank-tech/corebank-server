-- V202608201115__drop_version_from_transfer_limit.sql
-- 이체한도 (P1)
--
-- 낙관적 락(@Version)을 걷어내면서 더 이상 쓰이지 않는 version 컬럼을
-- 제거한다. 한도 변경과 이체 실행 모두 비관적 락(SELECT ... FOR UPDATE)
-- 으로 가기로 해 버전 검증이 필요 없다.
--
-- 이체는 transfer_limit 을 읽기만 하고 쓰지 않으므로, 버전을 검증하려면
-- 커밋 직전에 의미 없는 UPDATE 를 넣어야 한다. 그러면 같은 고객의 동시
-- 이체가 서로 충돌해 재시도가 생긴다.
--
-- 담기는 값이 락 카운터라 업무 데이터 손실은 없다.
-- ====================================================================

ALTER TABLE transfer_limit
    DROP COLUMN version;
